await page.getByRole('alert').waitFor();
assert.match(await page.getByRole('alert').innerText(),/id:/);
assert.equal(await page.locator('.data-imported-list li').count(),3);
await shot('desktop-settings');
for(const width of [360,390,430,600,768,900,1024,1440]) {
  await page.setViewportSize({width,height:900});
  for(const route of ['/',`/recipe/${exported.recipes[0].id}/overview`,`/recipe/${exported.recipes[0].id}/ingredients`,`/recipe/${exported.recipes[0].id}/timeline`,`/recipe/${exported.recipes[0].id}/cook`,'/shopping','/settings']) {
    await page.goto(`${base}#${route}`);
    await page.locator('main').waitFor();
    await overflow(`${width} ${route}`);
    if([390,768].includes(width)) await shot(`${width}-${route.split('/').at(-1)||'library'}`);
  }
}
await page.setViewportSize({width:390,height:844});
await page.goto(`${base}#/settings`);
