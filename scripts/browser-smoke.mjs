import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const base = process.env.COUNTERTOP_URL || 'http://127.0.0.1:5173/';
const output = '.qa';
await fs.mkdir(output, {recursive:true});
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'light',acceptDownloads:true});
const page = await context.newPage();
const errors = [];
page.on('pageerror',error=>errors.push(error.message));
async function overflow(label) {
  const result = await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(result.scroll<=result.width,`${label}: horizontal overflow ${JSON.stringify(result)}`);
}
async function shot(name) { await page.screenshot({path:`${output}/${name}.png`,fullPage:true}); }
await page.goto(base);
await page.getByRole('heading',{name:'Good food. All in one place.'}).waitFor();
await page.evaluate(()=>document.fonts.ready);
assert.equal(await page.locator('.recipe-card').count(),3);
assert.equal(await page.locator('.recipe-cover img').evaluateAll(images=>images.filter(image=>!image.complete||!image.naturalWidth).length),0);
await overflow('desktop library');
await shot('desktop-library');
await page.getByRole('textbox',{name:'Search recipes'}).fill('ricotta');
assert.equal(await page.locator('.recipe-card').count(),1);
await page.getByRole('button',{name:'Clear search'}).click();
await page.locator('.favorite-button').first().click();
await page.getByRole('button',{name:'Favorites',exact:true}).click();
assert.equal(await page.locator('.recipe-card').count(),1);
await page.getByRole('button',{name:'Favorites',exact:true}).click();
await page.getByRole('button',{name:'Let’s make this'}).click();
await page.locator('.recipe-heading').waitFor();
const servings = Number(await page.getByRole('spinbutton',{name:'Recipe servings'}).inputValue());
await page.getByRole('button',{name:'Increase servings'}).click();
assert.equal(Number(await page.getByRole('spinbutton',{name:'Recipe servings'}).inputValue()),servings+1);
await page.getByRole('button',{name:'Add to shopping list',exact:true}).click();
await page.getByRole('button',{name:'Ingredients',exact:true}).click();
await page.locator('.ingredient-check input').first().check();
assert.match(await page.locator('.checklist-progress').innerText(),/1 of/);
await page.reload();
await page.locator('.ingredient-check input').first().waitFor({state:'attached'});
assert.ok(await page.locator('.ingredient-check input').first().isChecked());
assert.equal(Number(await page.getByRole('spinbutton',{name:'Recipe servings'}).inputValue()),servings+1);
await page.getByRole('button',{name:'Timeline',exact:true}).click();
await page.locator('.timeline-event').first().waitFor();
assert.ok(await page.locator('.timeline-event').count()>8);
assert.ok(await page.locator('.parallel-label').count()>0);
await shot('desktop-timeline');
await page.getByRole('button',{name:'Cook',exact:true}).click();
await page.locator('.cook-focus-card').waitFor();
await page.getByRole('button',{name:'Begin cooking'}).click();
await page.getByRole('button',{name:/Start timer for/}).click();
await page.getByRole('button',{name:'Mark step complete'}).click();
await page.waitForTimeout(1200);
await page.reload();
await page.locator('.cook-focus-card').waitFor();
assert.match(await page.locator('.cook-progress-row').innerText(),/1 of/);
assert.equal(await page.locator('.cook-live-timer').count(),1);
assert.notEqual(await page.getByRole('timer').innerText(),'00:00');
await page.getByRole('button',{name:'Pause',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Resume',exact:true}).count(),1);
await shot('desktop-cooking');
page.once('dialog',dialog=>dialog.dismiss());
await page.getByRole('button',{name:'Reset cooking session'}).click();
assert.match(await page.locator('.cook-progress-row').innerText(),/1 of/);
await page.locator('.desktop-nav').getByRole('link',{name:/Shopping list/}).click();
await page.locator('.shopping-category').first().waitFor();
await page.locator('.shopping-item input').first().check();
await page.getByRole('button',{name:'Clear purchased'}).click();
assert.ok(await page.locator('.shopping-hidden-note').count());
await page.getByRole('button',{name:'Reset checklist'}).click();
assert.equal(await page.locator('.shopping-hidden-note').count(),0);
await page.getByRole('button',{name:/More servings of/}).click();
await page.getByRole('button',{name:'Copy list',exact:true}).click();
await expect.poll(async()=> (await page.getByText('Shopping list copied to clipboard.',{exact:true}).count())+(await page.getByRole('textbox',{name:'Shopping list text'}).count())).toBeGreaterThan(0);
await shot('desktop-shopping');
await page.locator('.desktop-nav').getByRole('link',{name:'Settings & data'}).click();
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button',{name:/Export your cookbook/}).click();
