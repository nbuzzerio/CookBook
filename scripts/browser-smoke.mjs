assert.ok(await recoveryPage.locator('.storage-warning').isVisible());
await browser.close();
console.log('PASS: library, search, favorites, recipe, scaling, persisted checklist/session/timer, timeline, shopping, copy, export/import, validation, dark mode, offline interactions, corruption recovery, and 56 responsive view checks.');
