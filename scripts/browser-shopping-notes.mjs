import { readLibrary } from './browser-storage.mjs';
import { expect } from '@playwright/test';
import { launchBrowser, localURL } from './browser-local.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const base=localURL(5173);
const recipe=JSON.parse(await fs.readFile('src/data/recipes/mushroom-meatloaf-dinner.json','utf8'));
const other=JSON.parse(await fs.readFile('src/data/recipes/spinach-mushroom-baked-ziti.json','utf8'));
await fs.mkdir('.qa/shopping-notes',{recursive:true});
const browser=await launchBrowser();
const context=await browser.newContext({viewport:{width:390,height:844},colorScheme:'light',reducedMotion:'reduce',acceptDownloads:true});
await context.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{value:undefined,configurable:true}));
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(base);
await page.evaluate(({recipe})=>{
  const save=(key,value)=>localStorage.setItem(`countertop:v1:${key}`,JSON.stringify({version:1,value}));
  save(`ingredients:${recipe.id}`,[recipe.ingredients[0].id]);
  save(`session:${recipe.id}`,{status:'paused',accumulatedMs:1500,startedAt:null,completedIds:[recipe.events[0].id],selectedId:recipe.events[0].id,timers:{}});
  save('shopping-plan',[{recipeId:recipe.id,servings:recipe.servings}]);
},{recipe});
await page.goto(`${base}#/recipe/${recipe.id}/overview`);
await page.reload();
await page.locator('.ingredient-preview .preview-group').first().waitFor();
const originalGroups=await page.locator('.ingredient-preview .preview-group').allTextContents();
const storedWork=await page.evaluate(id=>[localStorage.getItem(`countertop:v1:ingredients:${id}`),localStorage.getItem(`countertop:v1:session:${id}`)],recipe.id);
const note='Buy <b>the GF brand</b>.\n3 cups? Check the package label.';
const panel=page.getByRole('region',{name:'Shopping note',exact:true});
await panel.getByRole('button',{name:'Add note',exact:true}).click();
await expect(panel.getByRole('textbox',{name:'Your reminder'})).toBeFocused();
await panel.getByRole('textbox',{name:'Your reminder'}).fill(`  ${note}  `);
await panel.getByRole('button',{name:'Save note',exact:true}).click();
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await expect(panel.getByRole('button',{name:'Edit',exact:true})).toBeFocused();
assert.equal(await page.locator('.shopping-note b').count(),0);
assert.deepEqual(await page.locator('.ingredient-preview .preview-group').allTextContents(),originalGroups);
assert.deepEqual(await page.evaluate(id=>[localStorage.getItem(`countertop:v1:ingredients:${id}`),localStorage.getItem(`countertop:v1:session:${id}`)],recipe.id),storedWork);
await page.reload();
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await panel.getByRole('button',{name:'Edit',exact:true}).click();
await panel.getByRole('textbox',{name:'Your reminder'}).fill('Unsaved change.');
await panel.getByRole('button',{name:'Cancel',exact:true}).click();
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await panel.getByRole('button',{name:'Remove note',exact:true}).click();
await expect(page.locator('.shopping-note-text')).toHaveCount(0);
await panel.getByRole('button',{name:'Undo',exact:true}).click();
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await panel.getByRole('button',{name:'Edit',exact:true}).click();
await panel.getByRole('textbox',{name:'Your reminder'}).fill('This draft must not leak.');
await page.goto(`${base}#/recipe/${other.id}/overview`);
await panel.getByRole('button',{name:'Add note',exact:true}).click();
await expect(panel.getByRole('textbox',{name:'Your reminder'})).toHaveValue('');
await panel.getByRole('textbox',{name:'Your reminder'}).fill('Choose vegetarian cheese.');
await panel.getByRole('button',{name:'Save note',exact:true}).click();
await page.goto(`${base}#/recipe/${recipe.id}/overview`);
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await page.getByRole('button',{name:'Increase servings',exact:true}).click();
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await page.goto(`${base}#/shopping`);
await expect(page.locator('.shopping-recipe-note p')).toHaveText(note);
assert.equal(await page.locator('.shopping-recipe-note b').count(),0);
const groceryRows=await page.locator('.shopping-item').allTextContents();
await page.getByRole('button',{name:'Copy list',exact:true}).click();
await expect(page.getByRole('textbox',{name:'Shopping list text'})).toContainText(`Shopping note: Buy <b>the GF brand</b>.\n    3 cups? Check the package label.`);
await page.emulateMedia({media:'print'});
await expect(page.locator('.shopping-recipe-note')).toBeVisible();
await expect(page.getByRole('link',{name:'Edit note in recipe',exact:true})).toBeHidden();
await page.emulateMedia({media:'screen'});
await page.getByRole('button',{name:`Remove ${recipe.name} from shopping list`,exact:true}).click();
await page.goto(`${base}#/recipe/${recipe.id}/overview`);
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await page.getByRole('button',{name:'Add to shopping list',exact:true}).click();

await panel.getByRole('button',{name:'Edit',exact:true}).click();
await panel.getByRole('textbox',{name:'Your reminder'}).fill('x'.repeat(500));
await expect(panel).toContainText('0 characters remaining');
await panel.getByRole('button',{name:'Save note',exact:true}).click();
for(const width of [360,390,768,1280]){
  await page.setViewportSize({width,height:900});
  for(const route of [`/recipe/${recipe.id}/overview`,'/shopping']){
    await page.goto(`${base}#${route}`);
    await page.locator(route==='/shopping'?'.shopping-recipe-note':'.shopping-note-text').waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Long note overflow: ${width} ${route}`);
  }
}
assert.deepEqual(await page.locator('.shopping-item').allTextContents(),groceryRows);
await page.goto(`${base}#/recipe/${recipe.id}/overview`);
await panel.getByRole('button',{name:'Edit',exact:true}).click();
await panel.getByRole('textbox',{name:'Your reminder'}).fill(note);
await page.screenshot({path:'.qa/shopping-notes/editor-desktop.png',fullPage:true});
await panel.getByRole('button',{name:'Save note',exact:true}).click();
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Export recipe JSON',exact:true}).click();
const download=await downloadEvent;
await download.saveAs('.qa/shopping-notes/recipe.json');
assert.deepEqual(JSON.parse(await fs.readFile('.qa/shopping-notes/recipe.json','utf8')),recipe);
await page.goto(`${base}#/settings`);
const replacement={...recipe,name:`${recipe.name} (updated)`};
await page.getByLabel('Import recipe JSON file').setInputFiles({name:'replacement.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(replacement))});
await page.getByRole('radio',{name:/Replace matching recipes/}).check();
await page.getByRole('region',{name:'Review recipe import'}).getByRole('button',{name:'Import recipes'}).click();
await page.goto(`${base}#/recipe/${recipe.id}/overview`);
await expect(page.locator('.shopping-note-text')).toHaveText(note);
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Toggle light or dark theme'}).click();
await page.locator('.shopping-note').screenshot({path:'.qa/shopping-notes/note-dark.png'});
await page.goto(`${base}#/shopping`);
await page.locator('.shopping-recipe').screenshot({path:'.qa/shopping-notes/shopping-phone.png'});
await page.goto(`${base}#/settings`);
page.once('dialog',dialog=>dialog.accept());
await page.getByRole('button',{name:`Remove ${replacement.name}`,exact:true}).click();
assert.equal((await readLibrary(page)).privateNotes[recipe.id],undefined);
assert.equal((await readLibrary(page)).privateNotes[other.id],'Choose vegetarian cheese.');

const corrupt=await browser.newContext();
await corrupt.addInitScript(id=>localStorage.setItem('countertop:v1:shopping-notes',JSON.stringify({version:1,value:{[id]:123}})),recipe.id);
const corruptPage=await corrupt.newPage();
await corruptPage.goto(`${base}#/recipe/${recipe.id}/overview`);
await expect(corruptPage.getByRole('button',{name:'Add note',exact:true})).toBeVisible();
await expect(corruptPage.locator('.storage-warning')).toBeVisible();
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: shopping note save/edit/cancel/remove/undo, refresh, isolation, scaling independence, multiline copy/print, safe markup, long-note responsive layout, original JSON export, replacement retention, deletion cleanup, corrupted storage.');
